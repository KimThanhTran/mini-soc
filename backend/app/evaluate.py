"""Compares the rules, the anomaly model and both together on simulated, labelled traffic.

    python -m app.evaluate            # print the table
    python -m app.evaluate --write docs/ml-evaluation.md

Unit of evaluation is a source address: an attacker is detected if any alert names it, a benign source is a false positive
if any alert names it. Several seeds are run; the model is trained once on benign-only traffic from a separate seed.
"""
from __future__ import annotations

import argparse
import random
import statistics
from datetime import datetime, timedelta, timezone

from .engine import Engine
from .ml import Scorer, replay, to_event, train_default
from .rules import load_rules
from .simulation import CLASSIC, EVASIVE, SCENARIOS, benign

START = datetime(2026, 3, 1, 8, 0, tzinfo=timezone.utc)
MINUTES, INSTANCES = 120, 8


def build_test_set(seed: int):
    rng = random.Random(seed)
    items = benign(rng, START, MINUTES)
    for name, make in SCENARIOS.items():
        for _ in range(INSTANCES):
            items += make(rng, START + timedelta(seconds=rng.uniform(300, MINUTES * 60 - 1200)))
    return sorted(items, key=lambda i: i.ts)


def run(seed: int, scorer: Scorer):
    items = build_test_set(seed)
    events = [to_event(i.raw) for i in items]
    for n, ev in enumerate(events):
        ev["id"] = n
    # ground truth: label per source address (an address that does both is not generated)
    label = {i.actor: i.label for i in items if i.actor}
    attackers = {ip for ip, l in label.items() if l != "benign"}
    engine = Engine(load_rules())
    by_rules = {m.src_ip for ev in events for m in engine.process(ev) if m.src_ip}
    scored = [(ip, vec) for _, ip, vec in replay(events)]
    flags = scorer.score([v for _, v in scored])
    by_model = {ip for (ip, _), s in zip(scored, flags) if s < 0}
    return label, attackers, by_rules, by_model


def pr(flagged: set, attackers: set, label: dict):
    tp = len(flagged & attackers)
    fp = len({ip for ip in flagged if label.get(ip) == "benign"})
    precision = tp / (tp + fp) if tp + fp else 1.0
    return precision, tp / len(attackers), fp


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write")
    ap.add_argument("--seeds", type=int, default=5)
    args = ap.parse_args()
    scorer = train_default(seed=1)
    rows = {"rules": [], "model": [], "rules+model": []}
    per_scenario: dict[str, dict[str, list[float]]] = {n: {"rules": [], "model": [], "rules+model": []} for n in SCENARIOS}
    for seed in range(100, 100 + args.seeds):
        label, attackers, by_rules, by_model = run(seed, scorer)
        for name, flagged in (("rules", by_rules), ("model", by_model), ("rules+model", by_rules | by_model)):
            rows[name].append(pr(flagged, attackers, label))
            for scenario in SCENARIOS:
                ips = {ip for ip, l in label.items() if l == scenario}
                per_scenario[scenario][name].append(len(flagged & ips) / len(ips))
    mean = lambda xs: statistics.mean(xs)
    lines = [f"Seeds: {args.seeds}; per seed {MINUTES} min of benign traffic plus {INSTANCES} instances of each of "
             f"{len(SCENARIOS)} scenarios ({len(CLASSIC)} classic, {len(EVASIVE)} slow). Model trained on a separate benign-only seed.", "",
             "| Detector | Precision | Recall | False-positive benign sources (per seed) |", "|---|---|---|---|"]
    for name, vals in rows.items():
        lines.append(f"| {name} | {mean([v[0] for v in vals]):.2f} | {mean([v[1] for v in vals]):.2f} | "
                     f"{mean([v[2] for v in vals]):.1f} |")
    lines += ["", "Recall by scenario (share of attacker sources flagged):", "",
              "| Scenario | Kind | Rules | Model | Rules + model |", "|---|---|---|---|---|"]
    for s, d in per_scenario.items():
        kind = "slow" if s in EVASIVE else "classic"
        lines.append(f"| {s} | {kind} | {mean(d['rules']):.2f} | {mean(d['model']):.2f} | {mean(d['rules+model']):.2f} |")
    text = "\n".join(lines)
    print(text)
    if args.write:
        open(args.write, "w", encoding="utf-8").write("<!-- generated by `python -m app.evaluate --write` -->\n\n" + text + "\n")


if __name__ == "__main__":
    main()
